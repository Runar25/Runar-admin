    try:
        env = dict(os.environ, RUNAR_LAB_DST=tmp)
        r = subprocess.run([sys.executable, '-X', 'utf8', os.path.join(ROOT, 'build_crown_composer.py')], env=env,
                           capture_output=True, text=True, encoding='utf-8')
        if r.returncode != 0:
            raise SystemExit('build_crown_composer.py selhal: ' + (r.stderr or r.stdout)[-800:])
        html = io.open(os.path.join(tmp, 'crown-composer.html'), encoding='utf-8').read()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    a = html.index('<script>', html.index('runar-branch.js')) + len('<script>')
    b = html.rindex('</script>')
    return html[a:b]

